"""Build-only dependency: korean-lunar-calendar==0.3.1 (MIT, usingsky).
Run in an isolated venv; no package or network access is needed by the product.
See docs/work-calculator-rules.md for official calendar oracles and update review.
"""
import argparse
import json
from pathlib import Path
from importlib.metadata import version
from korean_lunar_calendar import KoreanLunarCalendar
assert version('korean-lunar-calendar') == '0.3.1'
calendar = KoreanLunarCalendar()
rows = {}
for year in range(2000, 2051):
    row = []
    for month, day in [(1, 1), (4, 8), (8, 15)]:
        assert calendar.setLunarDate(year, month, day, False)
        row.append(calendar.SolarIsoFormat())
    rows[str(year)] = row
body = '// Generated by scripts/generate-work-lunar-data.py; do not edit dates by hand.\n'
body += '// Ordinary (not leap) lunar months: New Year, Buddha, Chuseok. Generator 0.3.1.\n'
body += 'export const LUNAR_ANCHORS: Readonly<Record<number, readonly [string, string, string]>> = ' + json.dumps(rows, ensure_ascii=False, indent=2) + ';\n'
output = Path(__file__).resolve().parents[1] / 'src/features/work-calculator/lunarAnchors.ts'
args = argparse.ArgumentParser(); args.add_argument('--check', action='store_true'); options = args.parse_args()
if options.check:
    assert output.read_text() == body, 'Lunar data differs: regenerate and review official oracles'
else:
    output.write_text(body)
print('Verified 51 years / 153 ordinary-lunar anchors' if options.check else 'Generated 51 years / 153 ordinary-lunar anchors')

// Generates src/styles/theme.css from the finalized v3 palette.
// Source of truth: docs/jobs/todo/ui-redesign-rounds/probes-r2/palette-proposed.json
// (v3 N3 token table). Never hand-edit the generated CSS.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const palette = JSON.parse(fs.readFileSync(path.join(root, "docs/jobs/todo/ui-redesign-rounds/probes-r2/palette-proposed.json"), "utf8"));

const THEMES = ["light-coral", "dark-coral", "light-mint", "dark-mint"];
const SCHEME = { "light-coral": "light", "dark-coral": "dark", "light-mint": "light", "dark-mint": "dark" };
const kebab = (name) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

// Compat aliases: existing shadcn/legacy tokens re-pointed at semantic tokens.
// Per v3 N3: --accent keeps its "soft surface" meaning (brand primary is NOT
// aliased over it), --ring is focus, --destructive is errorText.
const ALIASES = Object.freeze({
  "--background": "var(--wl-bg)",
  "--foreground": "var(--wl-text)",
  "--card": "var(--wl-card-bg)",
  "--card-foreground": "var(--wl-text)",
  "--popover": "var(--wl-surface)",
  "--popover-foreground": "var(--wl-text)",
  // UI control --primary stays with the base layer (single indigo pair per
  // 1안); the per-theme brand token is --wl-brand below.
  "--secondary": "var(--wl-surface-muted)",
  "--secondary-foreground": "var(--wl-text)",
  "--muted": "var(--wl-surface-muted)",
  "--muted-foreground": "var(--wl-textSecondary)",
  "--accent": "var(--wl-accent-soft)",
  "--accent-foreground": "var(--wl-onSoft)",
  "--destructive": "var(--wl-errorText)",
  "--border": "var(--wl-border)",
  "--input": "var(--wl-controlBorder)",
  "--ring": "var(--wl-focus)",
  "--bg": "var(--wl-bg)",
  "--bg-elevated": "var(--wl-surface)",
  "--bg-solid": "var(--wl-surface)",
  "--bg-muted": "var(--wl-muted)",
  "--label": "var(--wl-text)",
  "--label-secondary": "var(--wl-textSecondary)",
  "--label-tertiary": "var(--wl-textSecondary)",
  "--separator": "var(--wl-border)",
});

const lines = [];
lines.push("/* Generated by scripts/generate-theme-tokens.mjs. Do not hand-edit. */");
lines.push("@layer theme;");
for (const theme of THEMES) {
  const tokens = palette[theme];
  if (!tokens) throw new Error(`Palette is missing theme ${theme}.`);
  lines.push(`:root[data-theme="${theme}"] {`);
  lines.push(`  color-scheme: ${SCHEME[theme]};`);
  // Token names stay verbatim (camelCase) to match palette-proposed.json and
  // the finalized lab/palette.css. Only new structural names use kebab-case.
  for (const [name, value] of Object.entries(tokens)) lines.push(`  --wl-${name}: ${value};`);
  // Structural aliases defined once per theme so every theme stays complete.
  lines.push("  --wl-sidebar-bg: var(--wl-surface);");
  lines.push("  --wl-card-bg: var(--wl-surface);");
  lines.push("  --wl-hero-bg: var(--wl-hero);");
  lines.push("  --wl-brand: var(--wl-primary);");
  lines.push("  --wl-brand-strong: var(--wl-hover);");
  lines.push("  --wl-accent-soft: var(--wl-soft);");
  lines.push("  --wl-surface-muted: var(--wl-muted);");
  lines.push("  --wl-textSecondary: var(--wl-secondary);");
  lines.push("  --wl-radius-sm: 12px;");
  lines.push("  --wl-radius-md: 14px;");
  lines.push("  --wl-radius-lg: 16px;");
  for (const [alias, target] of Object.entries(ALIASES)) lines.push(`  ${alias}: ${target};`);
  lines.push("}");
}
// Focus visibility is a 3px solid outline plus a 2px gap; ring opacity washes
// and shadows never substitute for it. Parents must not clip it.
lines.push(":root[data-theme] { color: var(--wl-text); background: var(--wl-bg); }");
lines.push("body { background: var(--wl-bg); color: var(--wl-text); }");
lines.push(":root[data-theme] :focus-visible { outline: 3px solid var(--wl-focus); outline-offset: 2px; }");
lines.push("@media print { :root[data-theme] { color-scheme: light; } :root[data-theme] * { box-shadow: none !important; text-shadow: none !important; } }");
lines.push("@media (forced-colors: active) { :root[data-theme] :focus-visible { outline: 3px solid CanvasText; } }");
lines.push("@media (prefers-reduced-motion: reduce) { :root[data-theme] *, :root[data-theme] *::before, :root[data-theme] *::after { animation-duration: 0.01ms !important; transition-duration: 0.01ms !important; } }");

const output = path.join(root, "src/styles/theme.css");
fs.writeFileSync(output, `${lines.join("\n")}\n`);
console.log(`Wrote ${path.relative(root, output)} (${THEMES.length} themes).`);
